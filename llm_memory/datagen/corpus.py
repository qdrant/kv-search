"""Document corpora: the training corpus and the Qdrant demo corpus, one JSONL line per document {id, kind, source, title, text}.

Training sources: Wikipedia (2 parquet shards of 20231101.en; half short, half long articles), CNN/DailyMail 3.0.0 (test and
validation), source code and markdown/rst docs of 29 GitHub repositories (search engines, vector databases, the Rust
ecosystem, C++ libraries, the CPython docs), and whole SQuAD train articles. Every document that mentions "qdrant" is dropped,
so the demo corpus stays unseen in training. Demo sources: qdrant/qdrant, qdrant/qdrant-client, and the documentation and
articles of qdrant/landing_page, all files (--per-repo 0 --keep-qdrant).

kind is wiki, news, code, docs or squad; documents are whole; id is "<kind>:<number>", numbered from --id-start after a final
shuffle. Repository files are listed with os.walk, whose order depends on the file system, so a rebuild on another machine
samples (and numbers) repository files differently; the released files are the reference.

  fetch   download the sources into the layout `build` reads: <src>/wiki, <src>/news, <src>/squad, <src>/repos/<name>
  build   sample the documents → docs.jsonl
  subset  the documents that facts are generated for: training — all wiki, news and squad and 40% of code and docs (seed
          123); Qdrant — a fixed quota per source and kind (seed 124), 500 documents

    python -m llm_memory.datagen.corpus fetch --corpus train --src data/sources/train
    python -m llm_memory.datagen.corpus build --src data/sources/train --skip-generated --id-start 500000 \
        --out data/train/docs.jsonl
    python -m llm_memory.datagen.corpus subset --docs data/train/docs.jsonl --out data/train/docs-facts.jsonl
"""
import argparse
import collections
import datetime
import glob
import json
import os
import random
import subprocess
import urllib.request

CODE_EXT = {".rs", ".py", ".go", ".c", ".cc", ".cpp", ".h", ".hpp", ".java", ".ts", ".js"}
DOC_EXT = {".md", ".rst"}
SKIP_DIRS = {".git", "node_modules", "vendor", "third_party", "target", "dist", "build", "__pycache__", ".github",
             "thirdparty", "singleheader", "single_include", "gtest", "googletest", "tpcds"}   # vendored code, amalgamations
GEN_MARKS = ("@generated", "do not edit", "autogenerated", "auto-generated", "generated by the protocol buffer",
             "this file was generated", "code generated by", "generated by")                     # marks of generated code

HF = "https://huggingface.co/datasets"
WIKI = [f"{HF}/wikimedia/wikipedia/resolve/main/20231101.en/train-{i}-of-00041.parquet" for i in ("00003", "00017")]
NEWS = [f"{HF}/abisee/cnn_dailymail/resolve/main/3.0.0/{s}-00000-of-00001.parquet" for s in ("test", "validation")]
SQUAD = "https://rajpurkar.github.io/SQuAD-explorer/dataset/train-v1.1.json"
TRAIN_REPOS = ("quickwit-oss/tantivy", "meilisearch/meilisearch", "lancedb/lancedb", "chroma-core/chroma", "weaviate/weaviate",
               "facebookresearch/faiss", "nmslib/hnswlib", "pgvector/pgvector", "milvus-io/milvus-docs", "tokio-rs/tokio",
               "serde-rs/serde", "tokio-rs/axum", "rust-lang/book", "rust-lang/rust-by-example", "hyperium/hyper",
               "BurntSushi/ripgrep",                                                    # cloned 2026-10-02 by 15:28 UTC
               "duckdb/duckdb", "google/leveldb", "abseil/abseil-cpp", "fmtlib/fmt", "nlohmann/json", "simdjson/simdjson",
               "google/re2", "spotify/annoy", "microsoft/SPTAG", "yahoojapan/NGT", "oneapi-src/oneTBB",
               "ninja-build/ninja")                                                     # cloned 2026-10-02 ~22:51 UTC
CPYTHON_DOCS = ("Doc/library", "Doc/tutorial", "Doc/howto")                             # sparse checkout of python/cpython
QDRANT_REPOS = ("qdrant/qdrant", "qdrant/qdrant-client")                                # cloned 2026-10-03 ~00:35 UTC
LANDING = {"qdrant_documentation": "qdrant-landing/content/documentation", "qdrant_articles": "qdrant-landing/content/articles"}
QDRANT_QUOTA = ("qdrant_documentation/docs=170,qdrant_documentation/code=60,qdrant_articles/docs=50,qdrant_qdrant/code=170,"
                "qdrant_qdrant-client/code=50")
# SQuAD articles held out by an earlier experiment of the research repo. Only the one-word titles match: SQuAD titles use
# underscores, so the multi-word ones never excluded anything. Kept as is because the released corpus was built this way.
SQUAD_HELD = {"Animal", "Armenians", "Biodiversity", "Buddhism", "Christian", "Circadian rhythm", "Crimean War", "Estonia",
              "Hard rock", "House music", "Napoleon", "New Delhi", "Oklahoma", "Order of the British Empire", "Poultry",
              "San Diego", "Separation of church and state in the United States",
              "Separation of powers under the United States Constitution", "Sumer", "Swaziland", "Textual criticism",
              "War on Terror"}


def git_clone(url, dst, before="", sparse=()):
    """Shallow clone of the default branch; with `before` (ISO time), checked out at its last commit before that time."""
    if os.path.isdir(dst):
        return
    base = ["git", "clone", "-q", "--single-branch"] + (["--filter=blob:none", "--sparse"] if sparse else [])
    if before:
        since = (datetime.date.fromisoformat(before[:10]) - datetime.timedelta(days=90)).isoformat()
        if subprocess.run(base + [f"--shallow-since={since}", url, dst]).returncode:     # no commits since then
            subprocess.run(base + ["--depth", "1", url, dst], check=True)
    else:
        subprocess.run(base + ["--depth", "1", url, dst], check=True)
    if sparse:
        subprocess.run(["git", "-C", dst, "sparse-checkout", "set", *sparse], check=True)
    if before:
        sha = subprocess.run(["git", "-C", dst, "rev-list", "-1", f"--before={before}", "HEAD"], check=True,
                             capture_output=True, text=True).stdout.strip()
        if not sha:
            raise SystemExit(f"{url}: no commit before {before} in the fetched history")
        subprocess.run(["git", "-C", dst, "checkout", "-q", sha], check=True)


def download(url, dst):
    if not os.path.exists(dst):
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        urllib.request.urlretrieve(url, dst + ".part")
        os.replace(dst + ".part", dst)


def fetch(a):
    repos = os.path.join(a.src, "repos")
    os.makedirs(repos, exist_ok=True)
    if a.corpus == "train":
        for sub, urls in (("wiki", WIKI), ("news", NEWS)):
            for u in urls:
                download(u, os.path.join(a.src, sub, os.path.basename(u)))
        download(SQUAD, os.path.join(a.src, "squad", "train-v1.1.json"))
        for r in TRAIN_REPOS:
            git_clone(f"https://github.com/{r}", os.path.join(repos, r.replace("/", "_")), a.before)
        git_clone("https://github.com/python/cpython", os.path.join(repos, "cpython"), a.before, CPYTHON_DOCS)
    else:
        for r in QDRANT_REPOS:
            git_clone(f"https://github.com/{r}", os.path.join(repos, r.replace("/", "_")), a.before)
        lp = os.path.join(a.src, "landing_page")                    # outside repos/: only two of its folders are sources
        git_clone("https://github.com/qdrant/landing_page", lp, a.before, ("qdrant-landing/content",))
        for name, sub in LANDING.items():
            if not os.path.lexists(os.path.join(repos, name)):
                os.symlink(os.path.abspath(os.path.join(lp, sub)), os.path.join(repos, name))


def build(a):
    only = set(x for x in a.only.split(",") if x)
    use = lambda src: not only or src in only
    rng = random.Random(a.seed)
    docs, dropped = [], collections.Counter()

    def add(kind, source, title, text):
        text = text.replace("\r\n", "\n").strip()
        if not a.keep_qdrant and ("qdrant" in text.lower() or "qdrant" in title.lower()):
            dropped["qdrant"] += 1
            return
        if len(text) < a.min_chars:
            dropped["short"] += 1
            return
        docs.append({"kind": kind, "source": source, "title": title, "text": text})

    if use("wiki") or use("news"):
        import pyarrow.parquet as pq

    # Wikipedia: as many short articles as long ones
    short, long_ = [], []
    for f in sorted(glob.glob(os.path.join(a.src, "wiki", "*.parquet"))) if use("wiki") else []:
        for r in pq.read_table(f, columns=["title", "text"]).to_pylist():
            if len(r["text"]) >= a.min_chars:
                (long_ if len(r["text"]) >= a.wiki_long else short).append(r)
    for pool in (short, long_):
        for r in rng.sample(pool, min(a.wiki // 2, len(pool))):
            add("wiki", "wikipedia", r["title"], r["text"])

    news = []
    for f in sorted(glob.glob(os.path.join(a.src, "news", "*.parquet"))) if use("news") else []:
        news += pq.read_table(f, columns=["article", "id"]).to_pylist()
    for r in rng.sample(news, min(a.news, len(news))):
        add("news", "cnn_dailymail", "news " + r["id"][:12], r["article"])

    # code and docs of the repositories
    for repo in sorted(glob.glob(os.path.join(a.src, "repos", "*"))) if use("repos") else []:
        name = os.path.basename(repo)
        files = []
        for root, dirs, fs in os.walk(repo):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
            for fn in fs:
                ext = os.path.splitext(fn)[1]
                if ext in CODE_EXT or ext in DOC_EXT:
                    files.append((os.path.join(root, fn), ext))
        for path, ext in rng.sample(files, len(files) if a.per_repo <= 0 else min(a.per_repo, len(files))):
            try:
                text = open(path, encoding="utf-8").read()
            except (UnicodeDecodeError, OSError):
                dropped["unreadable"] += 1
                continue
            if max((len(x) for x in text.split("\n")), default=0) > 1000:
                dropped["minified"] += 1
                continue
            if a.skip_generated and ext in CODE_EXT and any(m in text[:3000].lower() for m in GEN_MARKS):
                dropped["generated"] += 1
                continue
            add("docs" if ext in DOC_EXT else "code", name, name + "/" + os.path.relpath(path, repo), text)

    # SQuAD train, whole articles (paragraphs in order)
    sq = json.load(open(a.squad or os.path.join(a.src, "squad", "train-v1.1.json")))["data"] if use("squad") else []
    arts = [x for x in sq if x["title"] not in SQUAD_HELD]
    for x in rng.sample(arts, min(a.squad_articles, len(arts))):
        add("squad", "squad_train", x["title"].replace("_", " "), "\n\n".join(p["context"] for p in x["paragraphs"]))

    rng.shuffle(docs)
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f:
        for i, d in enumerate(docs):
            f.write(json.dumps({"id": f"{d['kind']}:{a.id_start + i}", **d}, ensure_ascii=False) + "\n")
    by = collections.defaultdict(lambda: [0, 0])
    for d in docs:
        by[d["kind"]][0] += 1
        by[d["kind"]][1] += len(d["text"])
    for k, (n, c) in sorted(by.items()):
        print(f"{k:<6} documents {n:>5}  characters {c / 1e6:6.2f}M")
    print(f"total {len(docs)}; dropped: {dict(dropped)}")


def subset(a):
    rng = random.Random(a.seed)
    n = 0
    with open(a.out, "w") as out:
        if a.quota:
            quota = {k: int(v) for k, v in (x.split("=") for x in (QDRANT_QUOTA if a.quota == "qdrant" else a.quota).split(","))}
            by = {}
            for line in open(a.docs):
                d = json.loads(line)
                by.setdefault(d["source"] + "/" + d["kind"], []).append(line)
            for key, lines in by.items():
                for line in rng.sample(lines, min(quota.get(key, 0), len(lines))):
                    out.write(line)
                    n += 1
        else:
            keep = set(a.keep_kinds.split(","))
            for line in open(a.docs):
                if json.loads(line)["kind"] in keep or rng.random() < a.frac:
                    out.write(line)
                    n += 1
    print(f"{n} documents → {a.out}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    f = sub.add_parser("fetch", help="download the sources")
    f.add_argument("--corpus", choices=["train", "qdrant"], default="train")
    f.add_argument("--src", default="data/sources/train")
    f.add_argument("--before", default="", help="ISO time: check repositories out at their last commit before it "
                                                "(released data: 2026-10-03T00:35:00Z for Qdrant); empty — current HEAD")
    b = sub.add_parser("build", help="sample documents → docs.jsonl")
    b.add_argument("--src", default="data/sources/train")
    b.add_argument("--squad", default="", help="SQuAD train-v1.1.json (default <src>/squad/train-v1.1.json)")
    b.add_argument("--only", default="", help="comma-separated: wiki,news,repos,squad (empty — all)")
    b.add_argument("--wiki", type=int, default=2400, help="Wikipedia articles (half short, half long)")
    b.add_argument("--wiki-long", type=int, default=6000, help="a long article has at least this many characters")
    b.add_argument("--news", type=int, default=1200)
    b.add_argument("--per-repo", type=int, default=400, help="at most this many files per repository (0 — all)")
    b.add_argument("--squad-articles", type=int, default=150)
    b.add_argument("--min-chars", type=int, default=400)
    b.add_argument("--skip-generated", action="store_true", help="drop code files with a generation mark in the first 3000 chars")
    b.add_argument("--keep-qdrant", action="store_true", help="keep documents mentioning qdrant (demo corpus only)")
    b.add_argument("--seed", type=int, default=114)
    b.add_argument("--id-start", type=int, default=0)
    b.add_argument("--out", default="data/train/docs.jsonl")
    s = sub.add_parser("subset", help="documents for fact generation")
    s.add_argument("--docs", default="data/train/docs.jsonl"); s.add_argument("--out", default="data/train/docs-facts.jsonl")
    s.add_argument("--keep-kinds", default="wiki,news,squad", help="kinds kept whole")
    s.add_argument("--frac", type=float, default=0.4, help="share of the other documents")
    s.add_argument("--quota", default="", help="'source/kind=n,...' or 'qdrant': a fixed sample per source and kind instead")
    s.add_argument("--seed", type=int, default=123)
    a = ap.parse_args()
    {"fetch": fetch, "build": build, "subset": subset}[a.cmd](a)


if __name__ == "__main__":
    main()
